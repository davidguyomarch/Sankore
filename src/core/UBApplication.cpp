void UBApplication::decorateActionMenu(QAction* action)
{
    for (QWidget* menuWidget : action->associatedWidgets())
    {
        QToolButton *tb = qobject_cast<QToolButton*>(menuWidget);

        if (tb && !tb->menu())
        {
            tb->setObjectName("ubButtonMenu");
            tb->setPopupMode(QToolButton::InstantPopup);
            QMenu* menu = new QMenu(mainWindow);

            QActionGroup* pageSizeGroup = new QActionGroup(mainWindow);
            pageSizeGroup->addAction(mainWindow->actionWidePageSize);
            pageSizeGroup->addAction(mainWindow->actionWidePageSize_16_10);
            pageSizeGroup->addAction(mainWindow->actionRegularPageSize);
            pageSizeGroup->addAction(mainWindow->actionCustomPageSize);

            QMenu* documentSizeMenu = menu->addMenu(QIcon(":/images/toolbar/svg/display.svg"),tr("Page Size"));
            documentSizeMenu->addAction(mainWindow->actionWidePageSize);
            documentSizeMenu->addAction(mainWindow->actionWidePageSize_16_10);
            documentSizeMenu->addAction(mainWindow->actionRegularPageSize);
            documentSizeMenu->addAction(mainWindow->actionCustomPageSize);
            menu->addAction(mainWindow->actionCut);
            menu->addAction(mainWindow->actionCopy);
            menu->addAction(mainWindow->actionPaste);
            menu->addAction(mainWindow->actionHideApplication);
            menu->addAction(mainWindow->actionSleep);

            menu->addSeparator();
            menu->addAction(mainWindow->actionPreferences);

            // Theme sub-menu
            QMenu* themeMenu = menu->addMenu(tr("Theme"));
            QActionGroup* themeGroup = new QActionGroup(themeMenu);
            themeGroup->setExclusive(true);

            QAction* actionThemeDark = themeMenu->addAction(tr("Dark (default)"));
            actionThemeDark->setCheckable(true);
            actionThemeDark->setData("dark");
            themeGroup->addAction(actionThemeDark);

            QAction* actionThemeClassic = themeMenu->addAction(tr("Classic (light)"));
            actionThemeClassic->setCheckable(true);
            actionThemeClassic->setData("classic");
            themeGroup->addAction(actionThemeClassic);

            QAction* actionThemeLight = themeMenu->addAction(tr("Light (modern)"));
            actionThemeLight->setCheckable(true);
            actionThemeLight->setData("light");
            themeGroup->addAction(actionThemeLight);

            QString currentTheme = mSettings->appTheme->get().toString();
            if (currentTheme == "classic")
                actionThemeClassic->setChecked(true);
            else if (currentTheme == "light")
                actionThemeLight->setChecked(true);
            else
                actionThemeDark->setChecked(true);

            connect(themeGroup, &QActionGroup::triggered, this, &UBApplication::themeChanged);

            menu->addAction(mainWindow->actionMultiScreen);

            menu->addSeparator();

            // Auto-OCR also available in menu (mirrors the palette toggle button)
            if (mRecognitionController && mRecognitionController->isAvailable() && mainWindow->actionAutoOcr)
                menu->addAction(mainWindow->actionAutoOcr);

            menu->addSeparator();
            menu->addAction(mainWindow->actionQuit);

            tb->setMenu(menu);
        }
    }
}


