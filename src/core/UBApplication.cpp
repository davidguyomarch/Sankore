QObject* UBApplication::staticMemoryCleaner = 0;

#if defined(Q_OS_MACOS)
static OSStatus ub_appleEventProcessor(const AppleEvent *ae, AppleEvent *event, long handlerRefCon)
{
    Q_UNUSED(event);
    OSType aeID = typeWildCard;
    OSType aeClass = typeWildCard;

    AEGetAttributePtr(ae, keyEventClassAttr, typeType, 0, &aeClass, sizeof(aeClass), 0);
    AEGetAttributePtr(ae, keyEventIDAttr, typeType, 0, &aeID, sizeof(aeID), 0);

    if (aeClass == kCoreEventClass && aeID == kAEReopenApplication)
    {
        // User clicked on Uniboard in the Dock
        ((UBApplicationController*)handlerRefCon)->hideDesktop();
        return noErr;
    }

    return eventNotHandledErr;
}
#endif


UBApplication::UBApplication(const QString &id, int &argc, char **argv) : QtSingleApplication(id, argc, argv)
  , mPreferencesController(nullptr)
  , mApplicationTranslator(nullptr)
  , mQtGuiTranslator(nullptr)
{
    staticMemoryCleaner = new QObject(0); // deleted in UBApplication destructor

    setOrganizationName("Sankore");
    setOrganizationDomain("sankore.org");
    setApplicationName("Open-Sankore");

    setApplicationVersion(QString(GIT_VERSION).isEmpty() ? UBVERSION : GIT_VERSION);

#if defined(Q_OS_MACOS) && !defined(QT_NO_DEBUG)
    CFStringRef shortVersion = (CFStringRef)CFBundleGetValueForInfoDictionaryKey(CFBundleGetMainBundle(), CFSTR("CFBundleShortVersionString"));
    const char *version = CFStringGetCStringPtr(shortVersion, kCFStringEncodingMacRoman);
    Q_ASSERT(version);
    setApplicationVersion(version);
#endif

    QStringList args = arguments();

    mIsVerbose = args.contains("-v")
        || args.contains("-verbose")
        || args.contains("verbose")
        || args.contains("-log")
        || args.contains("log");


    UBSettings *settings = UBSettings::settings();
    mSettings = settings;

    setupTranslators(args);

    UBResources::resources();

    if (!undoStack)
        undoStack = new QUndoStack(staticMemoryCleaner);

    UBPlatformUtils::init();

    connect(settings->appToolBarPositionedAtTop, &UBSetting::changed, this, &UBApplication::toolBarPositionChanged);
    connect(settings->appToolBarDisplayText, &UBSetting::changed, this, &UBApplication::toolBarDisplayTextChanged);
    updateProtoActionsState();

#ifndef Q_OS_MACOS
    setWindowIcon(QIcon(":/images/icon-proposal-2-board-stylus.svg"));
#endif

    // Load global stylesheet based on saved theme preference
    QString theme = UBSettings::settings()->appTheme->get().toString();
    QString qssResource = ":/themes/" + theme + "/style.qss";
    QFile styleFile(qssResource);
    if (styleFile.open(QIODevice::ReadOnly | QIODevice::Text))
    {
        setStyleSheet(styleFile.readAll());
        styleFile.close();
    }

    // Update palette colors to match the active theme at startup
    if (theme == "classic" || theme == "light")
    {
        UBSettings::paletteColor = QColor(245, 245, 245, 220);
        UBSettings::opaquePaletteColor = QColor(255, 255, 255, 240);
    }

    setStyle(new UBStyle()); // Style is owned and deleted by the application

    // Legacy Uniboard.css — only apply if no theme stylesheet was loaded
    if (styleSheet().isEmpty())
    {
        QString css = UBFileSystemUtils::readTextFile(UBPlatformUtils::applicationResourcesDirectory() + "/etc/Uniboard.css");
        if (css.length() > 0)
            setStyleSheet(css);
    }

    QApplication::setStartDragDistance(8); // default is 4, and is a bit small for tablets

    installEventFilter(this);

}


UBApplication::~UBApplication()
{
    UBPlatformUtils::destroy();

    UBFileSystemUtils::deleteAllTempDirCreatedDuringSession();

    delete mainWindow;
    mainWindow = 0;

    UBPersistenceManager::destroy();

    UBDownloadManager::destroy();

    UBDrawingController::destroy();

    UBSettings::destroy();

    UBCryptoUtils::destroy();

    UBToolsManager::destroy();

    if(mApplicationTranslator != nullptr){
        delete mApplicationTranslator;
        mApplicationTranslator = nullptr;
    }
    if(mQtGuiTranslator!=nullptr){
        delete mQtGuiTranslator;
        mQtGuiTranslator = nullptr;
    }

    delete staticMemoryCleaner;
    staticMemoryCleaner = 0;
}

QString UBApplication::checkLanguageAvailabilityForSankore(QString &language)
{
    QStringList availableTranslations = UBPlatformUtils::availableTranslations();
    if(availableTranslations.contains(language,Qt::CaseInsensitive))
        return language;
    else{
        if(language.length() > 2){
            QString shortLanguageCode = language.left(2);
            if(availableTranslations.contains(shortLanguageCode,Qt::CaseInsensitive))
                return shortLanguageCode;
        }
    }
    return QString("");
}

void UBApplication::setupTranslators(QStringList args)
{
    QString forcedLanguage("");
    if(args.contains("-lang"))
        forcedLanguage=args.at(args.indexOf("-lang") + 1);
    else{
        QString setLanguage = mSettings->appPreferredLanguage->get().toString();
        if(!setLanguage.isEmpty())
            forcedLanguage = setLanguage;
    }

    QString language("");

    if(!forcedLanguage.isEmpty())
        language = checkLanguageAvailabilityForSankore(forcedLanguage);

    if(language.isEmpty()){
        QString systemLanguage = UBPlatformUtils::systemLanguage();
        language = checkLanguageAvailabilityForSankore(systemLanguage);
    }

    if(language.isEmpty()){
        language = "en_US";
        //fallback if no translation are available
    }
    else{
        mApplicationTranslator = new QTranslator(this);
        mQtGuiTranslator = new QTranslator(this);
        mApplicationTranslator->load(UBPlatformUtils::translationPath(QString("sankore_"),language));
        installTranslator(mApplicationTranslator);

        QString qtGuiTranslationPath = UBPlatformUtils::translationPath("qt_", language);


        if(!QFile(qtGuiTranslationPath).exists()){
            qtGuiTranslationPath = UBPlatformUtils::translationPath("qt_", language.left(2));
            if(!QFile(qtGuiTranslationPath).exists())
                qtGuiTranslationPath = "";
        }

        if(!qtGuiTranslationPath.isEmpty()){
            mQtGuiTranslator->load(qtGuiTranslationPath);
            installTranslator(mQtGuiTranslator);
        }
        else
            qDebug() << "Qt gui translation in " << language << " is not available";
    }

    QLocale::setDefault(QLocale(language));
    qDebug() << "Running application in:" << language;
    //Claudio: hack to avoid the lost of translations.
    mSettings->init();
}

int UBApplication::exec(const QString& pFileToImport)
{

    QPixmapCache::setCacheLimit(1024 * 100);

    QString webDbPath = UBSettings::userDataDirectory() + "/web-databases";
    QDir webDbDir(webDbPath);
    if (!webDbDir.exists(webDbPath))
        webDbDir.mkpath(webDbPath);

    // Configure WebEngine default settings
#ifdef SANKORE_WEBENGINE
    QWebEngineSettings *gs = QWebEngineProfile::defaultProfile()->settings();
    gs->setAttribute(QWebEngineSettings::PluginsEnabled, true);
    gs->setAttribute(QWebEngineSettings::LocalStorageEnabled, true);
    gs->setAttribute(QWebEngineSettings::JavascriptCanAccessClipboard, true);
#endif

    mainWindow = new UBMainWindow(0, Qt::FramelessWindowHint);
    mainWindow->setAttribute(Qt::WA_NativeWindow, true);


    mainWindow->actionCopy->setShortcuts(QKeySequence::Copy);
    mainWindow->actionPaste->setShortcuts(QKeySequence::Paste);
    mainWindow->actionCut->setShortcuts(QKeySequence::Cut);


    connect(mainWindow->actionBoard, &QAction::triggered, this, [this]() { showBoard(); });
    connect(mainWindow->actionWeb, &QAction::triggered, this, [this]() { showInternet(); });
    connect(mainWindow->actionDocument, &QAction::triggered, this, [this]() { showDocument(); });
    connect(mainWindow->actionQuit, &QAction::triggered, this, [this]() { closing(); });
    connect(mainWindow, &UBMainWindow::closeEvent_Signal, this, &UBApplication::closeEvent);

    // Sync QML ThemeManager BEFORE creating palettes so QML starts with correct colors
    UBThemeManager::instance()->setCurrentTheme(mSettings->appTheme->get().toString());

    boardController = new UBBoardController(mainWindow);


    boardController->init();


    webController = new UBWebController(mainWindow);


    documentController = new UBDocumentController(mainWindow);


    boardController->paletteManager()->connectToDocumentController();

    UBApplication::mainWindow->actionPen->setChecked(false); // force re-trigger
    UBDrawingController::drawingController()->setStylusTool((int)UBStylusTool::Pen);

    applicationController = new UBApplicationController(boardController->controlView(),
                                                        boardController->displayView(),
                                                        mainWindow,
                                                        staticMemoryCleaner);



    connect(applicationController, &UBApplicationController::mainModeChanged,
            boardController->paletteManager(), &UBBoardPaletteManager::slot_changeMainMode);

    connect(applicationController, &UBApplicationController::desktopMode,
            boardController->paletteManager(), &UBBoardPaletteManager::slot_changeDesktopMode);



    connect(mainWindow->actionDesktop, &QAction::triggered, applicationController, &UBApplicationController::showDesktop);
    connect(mainWindow->actionDesktop, &QAction::triggered, this, [this]() { stopScript(); });
#ifndef Q_OS_MACOS
    connect(mainWindow->actionHideApplication, &QAction::triggered, mainWindow, []() { UBApplication::mainWindow->showMinimized(); });
#else
    connect(mainWindow->actionHideApplication, &QAction::triggered, this, [this]() { showMinimized(); });
#endif

    mPreferencesController = new UBPreferencesController(mainWindow);
    mRecognitionController = new UBRecognitionController(this);

    connect(mainWindow->actionPreferences, &QAction::triggered, mPreferencesController, [this]() { mPreferencesController->show(); });

    toolBarDisplayTextChanged(mSettings->appToolBarDisplayText->get());
    toolBarPositionChanged(mSettings->appToolBarPositionedAtTop->get());

    // Apply theme icons at startup
    reloadThemeIcons(mSettings->appTheme->get().toString());

    // Deferred reload: some palette buttons may not have updated yet
    // (Qt action-observer updates are asynchronous in some cases)
    QString startupTheme = mSettings->appTheme->get().toString();
    QTimer::singleShot(500, this, [this, startupTheme]() {
        reloadThemeIcons(startupTheme);

        // Also refresh dock palette backgrounds (they may have been created
        // before UBSettings::paletteColor was finalized for the active theme)
        if (boardController && boardController->paletteManager())
        {
            // Legacy dock palettes removed — QML V2 uses themeManager
        }
    });

    // Ensure all toolbar actions have tooltips (use text as fallback)
    QList<QToolBar*> toolbars = {mainWindow->boardToolBar, mainWindow->webToolBar, mainWindow->documentToolBar};
    for (QToolBar* toolbar : toolbars)
    {
        for (QAction* action : toolbar->actions())
        {
            if (!action->isSeparator() && action->toolTip().isEmpty())
                action->setToolTip(action->text());
        }
    }

    bool bUseMultiScreen = mSettings->appUseMultiscreen->get().toBool();
    mainWindow->actionMultiScreen->setChecked(bUseMultiScreen);
    connect(mainWindow->actionMultiScreen, &QAction::triggered, applicationController, &UBApplicationController::useMultiScreen);
    connect(mainWindow->actionWidePageSize, &QAction::triggered, boardController, &UBBoardController::setWidePageSize);
    connect(mainWindow->actionWidePageSize_16_10, &QAction::triggered, boardController, &UBBoardController::setWidePageSize16_10);
    connect(mainWindow->actionRegularPageSize, &QAction::triggered, boardController, &UBBoardController::setRegularPageSize);

    connect(mainWindow->actionCut, &QAction::triggered, applicationController, []() { UBApplication::applicationController->actionCut(); });
    connect(mainWindow->actionCopy, &QAction::triggered, applicationController, []() { UBApplication::applicationController->actionCopy(); });
    connect(mainWindow->actionPaste, &QAction::triggered, applicationController, []() { UBApplication::applicationController->actionPaste(); });

    applicationController->initScreenLayout(bUseMultiScreen);
    boardController->setupLayout();

    // Connect OCR zone selection from board view to recognition controller
    connect(boardController->controlView(), &UBBoardView::ocrZoneSelected,
            mRecognitionController, &UBRecognitionController::recognizeZone);

    // Connect Auto-OCR toggle (palette button + menu entry)
    if (mainWindow->actionAutoOcr)
        connect(mainWindow->actionAutoOcr, &QAction::toggled, this, &UBApplication::onAutoOcrToggled);

    // Notify OCR controller when a stroke finishes (mouse release on board)
    connect(boardController->controlView(), &UBBoardView::mouseRelease,
            mRecognitionController, [this]() { mRecognitionController->onStrokeFinished(); });

    if (pFileToImport.length() > 0)
        UBApplication::applicationController->importFile(pFileToImport);

#if defined(Q_OS_MACOS)
    static AEEventHandlerUPP ub_proc_ae_handlerUPP = AEEventHandlerUPP(ub_appleEventProcessor);
    AEInstallEventHandler(kCoreEventClass, kAEReopenApplication, ub_proc_ae_handlerUPP, SRefCon(UBApplication::applicationController), true);
#endif

    // Restored: call showBoard() to properly initialize the board view and palettes
    // In headless/offscreen mode, the window starts tiny (100x30) because there's
    // no window manager. Force a reasonable size BEFORE showBoard() creates palettes.
    if (mainWindow->width() < 800 || mainWindow->height() < 600) {
        QSize fallback(1920, 1080);
        QScreen* screen = QGuiApplication::primaryScreen();
        if (screen && screen->availableSize().width() >= 800)
            fallback = screen->availableSize();
        mainWindow->resize(fallback);
        qDebug() << "Headless mode: forced window resize to" << fallback;
    }
    showBoard();
    mainWindow->showMaximized();

    // Force Pen tool selection after all init is complete (deferred to ensure QML is ready)
    QTimer::singleShot(0, this, [this]() {
        if (boardController && boardController->paletteManager()
            && boardController->paletteManager()->toolController()) {
            auto* tc = boardController->paletteManager()->toolController();
            tc->setActiveTool(UBStylusTool::Pen);
            tc->setPenColorIndex(0); // Black — index 0 in the color palette
        } else {
            UBDrawingController::drawingController()->setStylusTool((int)UBStylusTool::Pen);
        }
    });

    onScreenCountChanged(1);
    return QApplication::exec();
}

